"""Load the standardized tables into PostGIS (started with `docker compose up -d`).

The schema lives in sql/01_schema.sql (applied automatically when the container is first
created). Loading is "replace everything" inside one transaction, so a failed load never
leaves half-written tables behind.
"""

from __future__ import annotations

import os

import pandas as pd
import psycopg

from bc_soil_background.paths import PROCESSED, RESULTS, ROOT

DB_URL = os.environ.get("BCSB_DATABASE_URL", "postgresql://soil:soil@localhost:5433/soil")

SAMPLE_COLS = [
    "sample_uid",
    "source_id",
    "source_type",
    "sample_id",
    "location_id",
    "site_name",
    "location_method",
    "location_uncertainty_m",
    "sample_media",
    "media_detail",
    "fill_or_native",
    "horizon",
    "depth_top_m",
    "depth_bottom_m",
    "sample_date",
    "is_duplicate",
    "duplicate_of",
    "size_fraction",
    "dq_flags",
]
RESULT_COLS = [
    "sample_uid",
    "analyte",
    "analyte_kind",
    "value",
    "unit",
    "non_detect",
    "detection_limit",
    "unit_raw",
    "value_raw",
    "method",
    "source_page",
    "unit_converted",
    "dq_flags",
]


def _records(df: pd.DataFrame, cols: list[str]) -> list[tuple]:
    """pandas NaN/NaT -> SQL NULL."""
    sub = df[cols].astype(object).where(df[cols].notna(), None)
    return [tuple(r) for r in sub.itertuples(index=False)]


def ensure_schema(conn: psycopg.Connection) -> None:
    conn.execute((ROOT / "sql" / "01_schema.sql").read_text())


def load(conn: psycopg.Connection) -> dict[str, int]:
    samples = pd.read_csv(PROCESSED / "samples.csv")
    results = pd.read_csv(PROCESSED / "results.csv")
    results["source_page"] = results.source_page.astype("Int64")
    with conn.transaction():
        conn.execute("TRUNCATE results, screening, samples RESTART IDENTITY CASCADE")
        cols = ", ".join(SAMPLE_COLS)
        marks = ", ".join(["%s"] * len(SAMPLE_COLS))
        with conn.cursor() as cur:
            cur.executemany(
                f"INSERT INTO samples ({cols}, geom) VALUES ({marks}, ST_SetSRID(ST_MakePoint(%s, %s), 3005))",
                [
                    r + (x, y)
                    for r, x, y in zip(_records(samples, SAMPLE_COLS), samples.x_albers, samples.y_albers, strict=True)
                ],
            )
            cols = ", ".join(RESULT_COLS)
            marks = ", ".join(["%s"] * len(RESULT_COLS))
            cur.executemany(f"INSERT INTO results ({cols}) VALUES ({marks})", _records(results, RESULT_COLS))
    counts = {}
    for table in ["samples", "results"]:
        counts[table] = conn.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
    return counts


def write_evidence(conn: psycopg.Connection) -> None:
    """Record what is in the database, straight from SQL, as evidence for the README."""
    by_source = conn.execute(
        """SELECT s.source_id, s.sample_media, count(DISTINCT s.sample_uid) AS samples,
                  count(r.result_id) AS results,
                  count(r.result_id) FILTER (WHERE r.analyte IN ('As','Cu','Zn')) AS as_cu_zn_results
           FROM samples s LEFT JOIN results r USING (sample_uid)
           GROUP BY 1, 2 ORDER BY 1"""
    ).fetchall()
    srids = conn.execute("SELECT DISTINCT ST_SRID(geom) FROM samples").fetchall()
    # Sanity check that geometry is in metres: R1 and R2 site points are both in Nanaimo.
    dist = conn.execute(
        """SELECT round(ST_Distance(a.geom, b.geom)::numeric, 0) FROM samples a, samples b
           WHERE a.source_id = 'R1_nanaimo_port_drive' AND b.source_id = 'R2_nanaimo_military_camp' LIMIT 1"""
    ).fetchone()
    version = conn.execute("SELECT postgis_lib_version()").fetchone()[0]
    lines = [
        "# PostGIS load (generated by `load/to_postgis.py`)",
        "",
        f"PostGIS {version}; geometry SRID(s): {[r[0] for r in srids]} (BC Albers, metres).",
        "",
        "| source_id | sample_media | samples | results | As/Cu/Zn results |",
        "|---|---|---|---|---|",
        *[f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in by_source],
        "",
        f"Sanity check: distance between the R1 and R2 site points = {dist[0]} m "
        "(both are in Nanaimo, so a few km is expected).",
        "",
        "Schema: [`sql/01_schema.sql`](../../sql/01_schema.sql).",
    ]
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "postgis_load.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    with psycopg.connect(DB_URL) as conn:
        ensure_schema(conn)
        print(load(conn))
        write_evidence(conn)
    print((RESULTS / "postgis_load.md").read_text())


if __name__ == "__main__":
    main()
